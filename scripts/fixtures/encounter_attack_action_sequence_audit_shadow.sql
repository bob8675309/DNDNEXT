\set ON_ERROR_STOP on
-- Disposable PG16 ONLY. Reuse all earlier equipment, spell, source and
-- participant/turn fixture setup without ever installing a live writer.
\i scripts/fixtures/encounter_hand_rules_constraints_shadow.sql

-- The earlier shadow fixtures don't execute or create the real attack writer.
-- Model the two canonical existing attack event tables' read surfaces only.
create table if not exists public.encounter_command_requests (
 request_id uuid primary key,
 encounter_id uuid not null,
 participant_id uuid not null,
 command_type text not null,
 requested_by uuid,
 result jsonb
);
create table if not exists public.encounter_combat_log (
 id bigint generated by default as identity primary key,
 encounter_id uuid not null,
 round integer not null,
 turn_index integer not null,
 actor_participant_id uuid,
 event_type text not null,
 detail jsonb not null default '{}'::jsonb
);
\i sql/20261026_09_encounter_attack_action_sequence_audit_shadow.sql

do $test$
declare
 p uuid:='dddddddd-0000-4000-8000-000000000001';
 other_p uuid:='dddddddd-0000-4000-8000-000000000002';
 e uuid:='ffffffff-0000-4000-8000-000000000001';
 req uuid:='bbbbbbbb-aaaa-4000-8000-000000000001';
 req_other uuid:='bbbbbbbb-aaaa-4000-8000-000000000002';
 req_legacy uuid:='bbbbbbbb-aaaa-4000-8000-000000000003';
 v jsonb;
 baseline_hands jsonb;
 after_hands jsonb;
 original_slots jsonb;
 final_slots jsonb;
 original_inventory jsonb;
 final_inventory jsonb;
 blocked boolean;
begin
 if has_function_privilege('anon',
  'private.encounter_attack_action_sequence_audit_shadow_v1(uuid)','EXECUTE')
 or has_function_privilege('authenticated',
  'private.encounter_attack_action_sequence_audit_shadow_v1(uuid)','EXECUTE')
 or not has_function_privilege('service_role',
  'private.encounter_attack_action_sequence_audit_shadow_v1(uuid)','EXECUTE')
 then raise exception 'Service-only canonical Attack action audit exposed to browser roles'; end if;

 select coalesce(jsonb_agg(to_jsonb(x) order by x.id),'[]'::jsonb)
  into original_inventory from public.inventory_items x;
 select coalesce(jsonb_agg(to_jsonb(x) order by x.participant_id,x.slot_level),'[]'::jsonb)
  into original_slots from public.encounter_spell_slots x;
 select coalesce(jsonb_agg(to_jsonb(x) order by x.participant_id,x.hand),'[]'::jsonb)
  into baseline_hands from public.encounter_hand_snapshot_items_shadow_v1 x;
 update public.encounters set status='active',active_participant_id=p,
  round=3,turn_index=1 where id=e;
 update public.encounter_participants set action_available=true where id=p;

 -- A blank authoritative attack log cannot manufacture attacks or
 -- Extra Attack proficiency/entitlement.
 v:=private.encounter_attack_action_sequence_audit_shadow_v1(p);
 if (v->>'currentTurnAttackEventCount')::integer<>0
 or v->>'canonicalActionAvailable'<>'true'
 or v->>'usesBooleanActionBudget'<>'true'
 or v->>'canonicalPerAttackSequenceStatePresent'<>'false'
 or v->>'extraAttackExecutionSupported'<>'false'
 or v->>'combatConsumerEnforced'<>'false'
 then raise exception 'Empty event log invented Attack action sequence %',v; end if;

 -- Recreate a successfully resolved canonical weapon attack log and its
 -- command request, then explicitly model the real writer spending Action.
 insert into public.encounter_command_requests(
   request_id,encounter_id,participant_id,command_type,requested_by,result
 ) values(req,e,p,'weapon_attack','aaaaaaaa-0000-4000-8000-000000000002','{}'::jsonb);
 insert into public.encounter_combat_log(
   encounter_id,round,turn_index,actor_participant_id,event_type,detail
 ) values(e,3,1,p,'weapon_attack',jsonb_build_object('requestId',req,'damage',7));
 update public.encounter_participants set action_available=false where id=p;
 v:=private.encounter_attack_action_sequence_audit_shadow_v1(p);
 if (v->>'currentTurnWeaponAttackLogCount')::integer<>1
 or (v->>'currentTurnUnarmedStrikeLogCount')::integer<>0
 or (v->>'requestLinkedAttackEventCount')::integer<>1
 or (v->>'unlinkedAttackEventCount')::integer<>0
 or v->>'canonicalActionAvailable'<>'false'
 or v->>'attackEquipBeforeAfterAttackIntegrated'<>'false'
 or v->>'extraAttackCountVerified'<>'false'
 or not (v->'readinessBlockers' ? 'single_weapon_or_unarmed_attack_consumes_full_action')
 then raise exception 'Real writer one attack/Action gap hidden %',v; end if;

 -- Other participant/round/turn logs must not change the current event
 -- sequence, even if a request ID is valid.
 insert into public.encounter_command_requests(
  request_id,encounter_id,participant_id,command_type,requested_by,result
 ) values(req_other,e,other_p,'attack','aaaaaaaa-0000-4000-8000-000000000002','{}'::jsonb);
 insert into public.encounter_combat_log(
  encounter_id,round,turn_index,actor_participant_id,event_type,detail
 ) values(e,3,1,other_p,'unarmed_strike',jsonb_build_object('requestId',req_other));
 insert into public.encounter_combat_log(
  encounter_id,round,turn_index,actor_participant_id,event_type,detail
 ) values(e,2,1,p,'unarmed_strike','{}'::jsonb),
 (e,3,0,p,'weapon_attack','{}'::jsonb);
 v:=private.encounter_attack_action_sequence_audit_shadow_v1(p);
 if (v->>'currentTurnAttackEventCount')::integer<>1
 or jsonb_array_length(v->'attackEvents')<>1
 then raise exception 'Attack events leaked across actor/round/turn %',v; end if;

 -- A historic unarmed event lacking a valid request is reported as
 -- unlinked rather than silently counting as a verified attack action.
 insert into public.encounter_combat_log(
  encounter_id,round,turn_index,actor_participant_id,event_type,detail
 ) values(e,3,1,p,'unarmed_strike',jsonb_build_object('requestId',req_legacy));
 v:=private.encounter_attack_action_sequence_audit_shadow_v1(p);
 if (v->>'currentTurnWeaponAttackLogCount')::integer<>1
 or (v->>'currentTurnUnarmedStrikeLogCount')::integer<>1
 or (v->>'currentTurnAttackEventCount')::integer<>2
 or (v->>'unlinkedAttackEventCount')::integer<>1
 or v->>'extraAttackExecutionSupported'<>'false'
 then raise exception 'Legacy/unlinked attack incorrectly proved Extra Attack support %',v; end if;

 -- A malformed/inactive next participant must not be treated as
 -- having an Attack action sequence from this participant.
 v:=private.encounter_attack_action_sequence_audit_shadow_v1(other_p);
 if (v->>'isActiveParticipant')<>'false'
 or (v->>'currentTurnWeaponAttackLogCount')::integer<>0
 or (v->>'currentTurnUnarmedStrikeLogCount')::integer<>1
 then raise exception 'Other participant not scoped independently %',v; end if;

 blocked:=false;
 begin perform private.encounter_attack_action_sequence_audit_shadow_v1(null);
 exception when invalid_parameter_value then blocked:=true; end;
 if not blocked then raise exception 'Null participant accepted'; end if;

 select coalesce(jsonb_agg(to_jsonb(x) order by x.id),'[]'::jsonb)
  into final_inventory from public.inventory_items x;
 select coalesce(jsonb_agg(to_jsonb(x) order by x.participant_id,x.slot_level),'[]'::jsonb)
  into final_slots from public.encounter_spell_slots x;
 select coalesce(jsonb_agg(to_jsonb(x) order by x.participant_id,x.hand),'[]'::jsonb)
  into after_hands from public.encounter_hand_snapshot_items_shadow_v1 x;
 if original_inventory is distinct from final_inventory
 or original_slots is distinct from final_slots
 or baseline_hands is distinct from after_hands then
   raise exception 'Read-only Attack sequencing diagnostic modified inventory, spells or hand shadow'; end if;
end $test$;
select 'Canonical Attack action gap, exact actor/turn event matching, unlinked requests and immutable equipment/slots passed' result;
