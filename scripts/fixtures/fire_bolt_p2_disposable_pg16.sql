create function public.encounter_targeting_context_internal_v1(p_caster uuid,p_target uuid)
returns jsonb language sql stable as $f$
select jsonb_build_object(
  'distanceFt',5*greatest(abs(c.q-t.q),abs(c.r-t.r),abs(c.q-t.q+c.r-t.r)),
  'hasLineOfSight',true,'coverAcBonus',0)
from public.encounter_participants c
cross join public.encounter_participants t
where c.id=p_caster and t.id=p_target
$f$;
