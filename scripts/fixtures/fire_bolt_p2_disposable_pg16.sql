create function public.encounter_apply_damage_internal_v1(
  p_target uuid,p_raw integer,p_type text
) returns jsonb language plpgsql as $f$
declare v_hp integer; begin
  update public.encounter_participants
  set current_hp=greatest(0,current_hp-p_raw)
  where id=p_target returning current_hp into v_hp;
  return jsonb_build_object('rawDamage',p_raw,'damage',p_raw,
    'damageType',p_type,'targetHp',v_hp,'targetTempHp',0);
end $f$;
