#!/usr/bin/env node
// No-cost, source-only research documentation snapshot. No network, secrets or AI.
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
export const GENERATED_PATH="docs/RESEARCH_BRANCH_STATUS.generated.md";
export function validResearchRef(ref) {
 return /^(?:research|agent)\/[a-zA-Z0-9_-]+(?:\/[a-zA-Z0-9._-]+)*$/.test(String(ref||""))
 && !String(ref).split("/").some(x=>x==="."||x===".."||x.startsWith("."));
}
const md=(s)=>String(s??"").replace(/[\r\n|<>`]/g," ").replace(/[\u0000-\u001f]/g," ").slice(0,240);
function git(root,...args) {
 return execFileSync("git",args,{cwd:root,encoding:"utf8",timeout:15000,maxBuffer:1500000}).trim();
}
export function renderBranchStatus(info) {
 assert.ok(validResearchRef(info.branch),"Only research/* or agent/* branch snapshots");
 assert.match(info.sha,/^[a-f0-9]{40}$/);
 assert.match(info.baseSha,/^[a-f0-9]{40}$/);
 const touched=info.lastPaths.filter(x=>x!=="docs/RESEARCH_BRANCH_STATUS.generated.md");
 const nonDocs=touched.filter(p=>!p.startsWith("docs/"));
 const manualDocs=touched.filter(p=>p.startsWith("docs/"));
 const changed=info.branchPaths.filter(p=>p!=="docs/RESEARCH_BRANCH_STATUS.generated.md");
 const docs=changed.filter(p=>p.startsWith("docs/"));
 const source=changed.filter(p=>!p.startsWith("docs/"));
 const summary=[
 "# DNDNext — automatically reconciled research-branch status","",
 "**Generated by the free documentation maintainer.** This is a SOURCE-COMMIT snapshot, not a production/deployment, browser or CI acceptance claim.",
 "",
 "| Field | Observed repository evidence |","|---|---|",
 "| Source branch | \`"+md(info.branch)+"\` |",
 "| Source commit before docs-only bot commit | \`"+info.sha+"\` |",
 "| Compared with | \`"+info.baseSha+"\` (main comparison base) |",
 "| Last source commit title | "+md(info.title)+" |",
 "| Files changed relative to main | "+changed.length+" ("+source.length+" non-docs; "+docs.length+" docs) |",
 "| Last source commit | "+touched.length+" files ("+nonDocs.length+" non-docs; "+manualDocs.length+" authored docs) |",
 "",
 "## Documentation freshness warning","",
 nonDocs.length&&!manualDocs.length?
 "**Manual living-doc reconciliation may be needed:** the latest source commit changed implementation/tests but did not update another authored \`docs/\` file. This generated status alone does not replace \`ACTIVE_WORK.md\`, \`PROJECT_STATE.md\`, \`SYSTEM_REGISTRY.json\` or a factual \`HANDOFF_LOG.md\` receipt.":
 manualDocs.length?
 "The latest source commit includes authored documentation. Verify correctness and any still-stale living docs against exact-head CI and deployed sources.":
 "The latest commit did not change non-docs source files. Do not infer a technical behavior change.",
 "",
 "## Latest source commit paths",""
 ];
 summary.push(...(touched.length?touched.slice(0,40).map(p=>"- \`"+md(p)+"\`"):["- No changed paths found"]));
 if(touched.length>40)summary.push("- … "+(touched.length-40)+" more");
 summary.push("","## Research-branch change inventory versus main","",
 ...changed.slice(0,50).map(p=>"- \`"+md(p)+"\`"));
 if(changed.length>50)summary.push("- … "+(changed.length-50)+" more");
 if(info.forge){
  const f=info.forge;
  summary.push("","## Forge source and authenticated evidence (branch-local only)","",
  "| Original trigger census | Staged DDL | Missing DDL | Mismatched definitions | Explicit targeted JWT receipts |",
  "|---:|---:|---:|---:|---:|",
  "| "+f.original+" | "+f.staged+" | "+f.missing+" | "+f.mismatches+" | "+f.receipts.length+" |",
  "","A staged definition is **not** a full source-body, JWT, COMMIT, concurrency, production RLS or browser acceptance claim.");
  for(const e of f.receipts){
   summary.push("- \`"+md(e.trigger)+"\`: \`"+md(e.tests)+"\` at independently verified \`"+e.testedHead+"\` ([CI run](https://github.com/bob8675309/DNDNEXT/actions/runs/"+e.actionsRunId+")). "+md(e.scope));
  }
 }
 summary.push("","## Trust and update procedure","",
 "- The source SHA above identifies the code being summarized; a later bot-generated docs-only commit changes the PR head but **not code**. GitHub's default \`GITHUB_TOKEN\` does not start a second CI run for that docs-only commit.",
 "- For exact test status, inspect Actions results on the recorded **source SHA**. Do not assume CI passed, infer main deployment, or mark an original trigger as fully accepted from this snapshot.",
 "- Manual/AI-assisted changes must update the relevant living documents and append a factual \`HANDOFF_LOG.md\` receipt as part of the **same source patch**; the bot snapshot helps identify omissions but does not invent claims.",
 "- Owner-approved docs-only publishing is permitted **only** to this path on \`research/*\` or \`agent/*\` with atomic expected-head verification; never to \`main\`, production SQL, runtime code or historical logs.",
 "- See [DOCUMENT_LIFECYCLE.md](DOCUMENT_LIFECYCLE.md) before changing or retiring historical documents. No automatic deletion.",
 "");
 return summary.join("\n");
}
export async function collect(root=ROOT) {
 const sha=git(root,"rev-parse","HEAD");
 const branch=process.env.DOCS_TARGET_BRANCH||git(root,"symbolic-ref","--short","HEAD");
 assert.ok(validResearchRef(branch),"Unsafe docs branch "+branch);
 const baseline=(()=>{for(const ref of ["refs/remotes/origin/main","refs/heads/main"]){try{return git(root,"rev-parse","--verify",ref)}catch{}}throw Error("Missing main comparison source, fail closed");})();
 const merge=git(root,"merge-base",baseline,sha);
 const branchPaths=git(root,"diff","--name-only",merge,sha).split("\n").filter(Boolean);
 const lastPaths=git(root,"diff-tree","--no-commit-id","--name-only","-r",sha).split("\n").filter(Boolean);
 const title=git(root,"log","-1","--format=%s");
 let forge=null;
 if(existsSync(path.join(root,"scripts/agents/forge_trigger_acceptance_receipts.json"))){
  const audit=await import("./forge_trigger_audit.mjs");
  const ledger=await import("./forge_trigger_acceptance_ledger.mjs");
  const original=audit.inspectForgeCheckout(root);
  const evidence=JSON.parse(readFileSync(path.join(root,"scripts/agents/forge_trigger_acceptance_receipts.json"),"utf8"));
  const l=ledger.buildLedger(original,evidence);
  forge={original:l.original,staged:l.staged,missing:l.missing,mismatches:l.mismatches,
    receipts:l.rows.filter(r=>r.evidence).map(r=>({trigger:r.name,...r.evidence}))};
  assert.equal(forge.mismatches,0,"Original trigger inventory mismatch blocks snapshot");
 }
 return {branch,sha,baseSha:merge,branchPaths,lastPaths,title,forge};
}
if(process.argv[1]&&fileURLToPath(import.meta.url)===path.resolve(process.argv[1])){
 try{
  const out=path.resolve(process.argv[2]||path.join(ROOT,GENERATED_PATH));
  assert.ok(out.endsWith("/"+GENERATED_PATH)||out.endsWith("/RESEARCH_BRANCH_STATUS.generated.md"),"Only generated research status output allowed");
  const info=await collect(ROOT);
  mkdirSync(path.dirname(out),{recursive:true});
  writeFileSync(out,renderBranchStatus(info),"utf8");
  console.log("PASS no-cost source-only research docs snapshot "+info.branch+" @ "+info.sha+"; "+(info.forge?info.forge.staged+"/31 original DDL":"no Forge receipt ledger"));
 }catch(e){console.error("FAIL docs auto-sync: "+e.message);process.exitCode=1}
}
