// Original private attack roll, real GoTrue JWT, disposable PG17 only.
import assert from "node:assert/strict";
import {randomUUID} from "node:crypto";
import {spawnSync} from "node:child_process";
import {createClient} from "@supabase/supabase-js";
const env=process.env;
for(const [k,v] of Object.entries({GITHUB_ACTIONS:"true",CI:"true",DNDNEXT_P13_LOCAL_CI_CONFIRM:"P13_DISPOSABLE_REAL_GOTRUE_ONLY",PGHOST:"127.0.0.1",PGPORT:"54322",PGDATABASE:"postgres"}))assert.equal(env[k],v);
assert.match(env.DNDNEXT_P13_LOCAL_URL||"",/^http:\/\/127\.0\.0\.1:54321\/?$/);
assert.ok(env.DNDNEXT_P13_LOCAL_ANON_KEY);
const id=n=>"00000000-0000-0000-0000-"+String(n).padStart(12,"0");
function db(sql){
 const v=spawnSync("psql",["-X","-v","ON_ERROR_STOP=1","-qAt","-c",sql],{encoding:"utf8",timeout:15000,env:{...env,PGUSER:"postgres"}});
 if(v.status!==0)throw Error("Disposable PostgreSQL assertion failed: "+v.stderr);
 return v.stdout.trim();
}
const num=sql=>Number(db(sql));
const make=()=>createClient(env.DNDNEXT_P13_LOCAL_URL,env.DNDNEXT_P13_LOCAL_ANON_KEY,{auth:{persistSession:false,autoRefreshToken:false,detectSessionInUrl:false}});
const attack=(who,n,req)=>who.rpc("p13_candidate_unarmed_reaction_research_v1",{p_window_id:id(5000+10*n),p_inventory_item_id:null,p_request_id:req});
const deny=(result,pattern,label)=>{assert.ok(result.error,label+" unexpectedly accepted");assert.match(result.error.message,pattern,label+": "+result.error.message);};
const status=n=>db("SELECT reaction_available FROM public.encounter_participants WHERE id='"+id(1001+10*n)+"'");
const hp=n=>num("SELECT current_hp FROM public.encounter_participants WHERE id='"+id(1000+10*n)+"'");
const fx=n=>num("SELECT count(*) FROM public.encounter_timed_effects WHERE encounter_id='"+id(900+n)+"'");
const logs=n=>num("SELECT count(*) FROM public.encounter_combat_log WHERE encounter_id='"+id(900+n)+"' AND event_type='effect_consumed'");
function inspect(result,n){
 assert.ifError(result.error);
 const x=result.data.attack.attackRoll;
 assert.ok(x,"Missing ORIGINAL roll payload for "+n);
 assert.ok(Number.isInteger(x.roll)&&x.roll>=1&&x.roll<=20);
 assert.ok(Number.isInteger(x.firstRoll)&&x.firstRoll>=1&&x.firstRoll<=20);
 assert.equal(result.data.attack.roll,x.roll);
 assert.equal(status(n),"f");
 assert.equal(result.data.attack.rawDamage,result.data.attack.hit?4:0);
 assert.equal(hp(n),20-result.data.attack.damage.damage);
 return x;
}
const pwd="TempP13Effects-"+randomUUID()+"-X9!",users=[];
for(const label of ["GM","REACTOR","OUTSIDER"]){
 const who=make(),email="p13-effects-"+randomUUID()+"@example.invalid";
 const a=await who.auth.signUp({email,password:pwd});assert.ifError(a.error);
 const b=await who.auth.signInWithPassword({email,password:pwd});assert.ifError(b.error);
 const claims=await who.auth.getClaims(),me=await who.auth.getUser();
 assert.ifError(claims.error);assert.ifError(me.error);
 assert.equal(claims.data.claims.sub,me.data.user.id);
 assert.equal(claims.data.claims.role,"authenticated");
 assert.notEqual(claims.data.claims.is_anonymous,true);
 users.push({who,uid:me.data.user.id,label});
}
const [gm,reactor,outsider]=users;
assert.equal(new Set(users.map(z=>z.uid)).size,3);
db("INSERT INTO public.p13_auth_admins(user_id) VALUES('"+gm.uid+"')");
db("UPDATE public.encounter_participants SET controller_user_id='"+reactor.uid+"' WHERE id IN ("+Array.from({length:7},(_,i)=>"'"+id(1201+i*10)+"'").join(",")+")");
console.log("PASS 106: original random attack roll and 3 distinct signed JWTs");
