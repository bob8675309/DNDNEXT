assert.equal(ar.guidingBoltAdvantage,true);assert.equal(ar.guidingBoltEffectConsumed,true);
assert.equal(ar.advantage,true);assert.equal(ar.disadvantage,false);
assert.equal(ar.roll,Math.max(ar.firstRoll,ar.secondRoll));
assert.equal(fx(20),0);assert.equal(logs(20),1);
console.log("PASS 107: original Guiding Bolt effect is consumed for D20 advantage");
const dis=await attack(reactor.who,21,randomUUID()),dr=inspect(dis,21);
assert.equal(dr.viciousMockeryDisadvantage,true);assert.equal(dr.viciousMockeryEffectConsumed,true);
assert.equal(dr.disadvantage,true);assert.equal(dr.advantage,false);
assert.equal(dr.roll,Math.min(dr.firstRoll,dr.secondRoll));
assert.equal(fx(21),0);assert.equal(logs(21),1);
console.log("PASS 108: original Vicious Mockery effect yields D20 disadvantage");
const both=await attack(reactor.who,22,randomUUID()),br=inspect(both,22);
assert.equal(br.guidingBoltEffectConsumed,true);assert.equal(br.viciousMockeryEffectConsumed,true);
assert.equal(br.advantageCanceledByDisadvantage,true);
assert.equal(br.advantage,false);assert.equal(br.disadvantage,false);assert.equal(br.secondRoll,null);
assert.equal(fx(22),0);assert.equal(logs(22),2);
console.log("PASS 109: original effects cancel advantage/disadvantage and both expire");
const retry=await attack(reactor.who,20,advId);
assert.ifError(retry.error);assert.deepEqual(retry.data,adv.data);
assert.equal(fx(20),0);assert.equal(logs(20),1);
console.log("PASS 110: exact replay does not reroll dice or consume an effect");
const sameId=randomUUID(),[a,b]=await Promise.all([attack(reactor.who,23,sameId),attack(reactor.who,23,sameId)]);
assert.ifError(a.error);assert.ifError(b.error);assert.deepEqual(a.data,b.data);
inspect(a,23);assert.equal(fx(23),0);assert.equal(logs(23),1);
assert.equal(num("SELECT count(*) FROM private.p13_guarded_commands WHERE request_id='"+sameId+"' AND result IS NOT NULL"),1);
console.log("PASS 111: simultaneous exact JWT replay consumes one timed effect");
deny(await attack(reactor.who,25,randomUUID()),/opportunity attacks are suppressed/i,"Suppressed reaction");
assert.equal(fx(25),2);assert.equal(hp(25),20);assert.equal(status(25),"t");
assert.equal(num("SELECT count(*) FROM public.encounter_command_requests WHERE encounter_id='"+id(925)+"'"),0);
