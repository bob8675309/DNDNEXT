const normal=await attack(reactor.who,24,randomUUID()),nr=inspect(normal,24);
assert.equal(nr.advantage,false);assert.equal(nr.disadvantage,false);
assert.equal(nr.secondRoll,null);assert.equal(logs(24),0);
